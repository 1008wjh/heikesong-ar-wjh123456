def post(base, path, body):
    req = urllib.request.Request(
        base + path, data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    return json.load(urllib.request.urlopen(req, timeout=60))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--backend", default="http://127.0.0.1:8765")
    args = ap.parse_args()
    base = args.backend.rstrip("/")

    existing = {p["name"] for p in json.load(
        urllib.request.urlopen(base + "/api/people", timeout=30))["people"]}
    created = updated = 0
    for p in PEOPLE:
        body = {"name": p["name"], "role": p["role"], "info": p["info"],
                "simple": p.get("simple") or {}, "complex": p.get("complex") or {}}
        r = post(base, "/api/people/save", body)
        if not r.get("ok"):
            print("  FAIL %s: %s" % (p["name"], r.get("error")))
            continue
        if p["name"] in existing:
            updated += 1
        else:
            created += 1
            existing.add(p["name"])
    print("新增 %d，更新 %d，共 %d 条" % (created, updated, len(PEOPLE)))
    total = len(json.load(urllib.request.urlopen(base + "/api/people", timeout=30))["people"])
    print("库里现在 %d 人" % total)
    return 0


